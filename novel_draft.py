style.paragraph_format.first_line_indent = Cm(0.74)  # 2 characters indent

# Title style
title_style = doc.styles['Title']
title_style.font.size = Pt(22)
title_style.font.color.rgb = RGBColor(0, 0, 0)
title_style.font.bold = True
title_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
title_style.paragraph_format.space_before = Cm(3)
title_style.paragraph_format.space_after = Cm(1)

# Heading styles
for i in range(1, 3):
    h = doc.styles[f'Heading {i}']
    h.font.size = Pt(16) if i == 1 else Pt(14)
    h.font.bold = True
    h.font.color.rgb = RGBColor(0, 0, 0)
    h.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    h.paragraph_format.space_before = Cm(1.5)
    h.paragraph_format.space_after = Cm(1)

def add_paragraph(text, bold=False, align=None, size=None, space_before=None, space_after=None):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    run = p.add_run(text)
    run.font.size = size or Pt(12)
    run.font.name = '宋体'
    run.bold = bold
    if space_before:
        p.paragraph_format.space_before = Cm(space_before)
    if space_after:
        p.paragraph_format.space_after = Cm(space_after)
    return p

def add_chapter(chapter_num, title, content_paragraphs):
    """Add a chapter with number, title and content."""
    add_paragraph(f"第{chapter_num}章", bold=True, size=Pt(16), align=WD_ALIGN_PARAGRAPH.CENTER, space_before=2, space_after=0.3)
    add_paragraph(title, bold=True, size=Pt(16), align=WD_ALIGN_PARAGRAPH.CENTER, space_before=0, space_after=1.5)
    for text in content_paragraphs:
        add_paragraph(text)

