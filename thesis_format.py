add_heading_text(doc, '结语：《耶稣传》对新时代基督教中国化的启示', 1)
write_body(doc, '''《耶稣传》中所蕴涵的中国化思想与实践路径，虽已历经近一个世纪的沧桑，却并未因时代的变迁而失去其现实价值。在当代中国，推进基督教中国化已成为宗教工作的核心主线与根本方向。赵紫宸这位基督教中国化先驱的思想遗产，为我们新时代基督教中国化提供了许多的启示。''')

write_body(doc, '''赵紫宸《耶稣传》中国化实践最为核心的方法论，是对基督教信仰进行"本真"与"非本真"的区分与剥离。他所秉持的逻辑是：基督教的本真并非那些包裹其外的西方教会仪式、教义信条、组织制度和建筑形式，而是耶稣基督本人的人格精神。赵紫宸曾言："基督教不是书本之宗教，乃以耶稣基督为中心、以生命根基为依归之宗教"。赵紫宸一方面从受西方近代自由主义神学影响的神学方法出发，大胆剥离了在他看来属于犹太民族历史产物和后世神学穿凿附会的部分。另一方面，他又以耶稣的人格精神为不可动摇的根基，以此统摄全书的叙事逻辑。赵紫宸的这种"回归本真"，为今天的中国基督教中国化提供了宝贵的方法论参考。今天推进基督教中国化的进程中，同样需要找到信仰"本真"与文化"表达"之间的平衡点，中国基督教需要在积极汲取中华优秀传统文化养分、与社会主义核心价值观相融合的同时，也需要清醒地认识和把握自身信仰的核心本质，既不能让信仰因固守外在形式而在中国文化中水土不服，也不能让信仰的"本真"因过度适应而被稀释消解。''')

write_body(doc, '''赵紫宸在《耶稣传》中展现的伦理化神学路径。在《基督教与中国文化》中，他认为新时代的宗教，是要合乎伦理的；是重人格的；也是合乎社会的。《耶稣传》中他通过将基督教信仰的核心教义进行伦理化诠释，使基督教能够以中国人熟悉的道德话语进行表达，从而增强了信仰的文化可接受性。2025年，习近平总书记在中共中央政治局第二十二次集体学习时强调，系统推进宗教中国化是要实现从"外在融入"到"内在契合"的深度转变，需要挖掘基督教教义中与中华文化核心价值的共通点，并以中华文化语境重构教义阐释体系。这一论述与赵紫宸近一个世纪前的工作形成了跨越时空的呼应。赵紫宸将基督教与儒家深度贯通的实践，为今天以中华文化语境重构基督教神学阐释体系提供了可借鉴的经验，即要深入到信仰的伦理内核，找到基督教教义与中华优秀传统文化在精神实质上的共振点，再以中华文化特有的概念范畴和思维方式来重新诠释，从而实现真正的深度契合。在这过程中，一方面，要善于发现基督教与中国文化的共通之处，以此作为对话的起点；另一方面，也要尊重两者的差异，通过"存异"来保持各自的独特性。以共同点来切入，以相异处来补充。''')

write_body(doc, '''赵紫宸在《耶稣传》中也展现了强烈现实关怀。他所呈现的耶稣形象，是一个为社会重建而奋斗的伦理领袖和人格典范。他写作《耶稣传》的一个重要目的，就是为处于民族危机中的中国社会提供精神出路，使基督教成为"救国"的资源而非"洋教"的标签。他认为，国家的强弱、社会的兴衰，根本在于国民的人格质量，因此，基督教在中国所能作出的最大贡献，不是提供彼岸的寄托，而是通过效法耶稣基督的完美人格，改造国民的精神品质，实现人格的更新与重建，从而推动整个社会的改革与进步。''')

write_body(doc, '''基督教对于中华民族复兴能有什么贡献，这是当时中国教会必须回答的问题。在当代中国，基督教同样需要回答"基督教对于中华民族伟大复兴能有什么贡献"这一问题。今天，中国已不再是那个积贫积弱、饱受欺凌的旧中国，但赵紫宸关于基督教应当呈现其社会价值的基本洞见，对今天的基督教中国化仍具启发意义。基督教中国化不应该只是理论层面的神学建构，必须回应时代的需求，要在实践层面展现基督教对社会的积极贡献。基督教中国化的最终目的，不是简单地使基督教"穿上华服"，应当积极参与国民道德建设、社会心理建设，在培育积极向上的社会心态、促进人际和谐、服务社会公益等方面发挥独特作用。''')

write_body(doc, '''赵紫宸在《耶稣传》中展现出的强烈主体意识，也值得今天的中国基督教深思。赵紫宸有意识地从中国人"独到的眼光"出发来诠释耶稣，坚决"脱西洋的窠臼"，而不是简单复制西方神学的结论。在赵紫宸笔下，耶稣被塑造为中国人心目中完善的君子、圣人的形象，这是中国基督徒第一次以自身文化为主体来诠释基督教信仰的基本事实。基督教中国化不是被动接受西方传教士所诠释的基督教，是中国基督徒作为诠释信仰的主体，从中国文化处境出发，以中国人的生命经验和精神需要为基点，来重新理解、表达和实践基督教信仰。正如赵紫宸在《耶稣传》所言，他写《耶稣传》，是要"按我所认识的告诉人"，而这个"我"，是作为中国基督徒的"我"。另言，任何读者都难免带有自身的视角，关键在于让自身视角的"本色玻璃磨得准确些，以便不把耶稣看得太模糊"。''')

write_body(doc, '''当然《耶稣传》作为精英文本，也提醒今天基督教中国要注意精英与大众张力。正如本文第三章所分析的，这种精英化的路径在收获学界与文化界热烈反响的同时，也在一定程度上与基层教会普通信徒的信仰需求产生了隔阂。这一张力提醒我们：基督教中国化不能仅停留在"学府式"的神学建构层面，更不能将"中国化"窄化为少数知识分子的文化诠释游戏。基督教的中国化，必须同时向下扎根，深入民间信仰生活，了解普通信徒的灵性需求与表达方式。如何在保持神学深度与文化对话品质的同时，创造出信众喜闻乐见的信仰表达形式，这是赵紫宸留给当代教会的一个未完成的课题。''')

write_body(doc, '''《耶稣传》的背后是一套以人格为核心、四大神学板块（上帝观、基督论、救赎观、天国观）环环相扣，整体系统的神学框架。上帝，因有人格而可亲可近（伦理化）；耶稣，因人格完美而可效法（人本化）；救赎，因人格重建而可实践（修身化）；天国，因人格聚集而可实现（大同化）。这套系统使《耶稣传》的中国化不趋于表面的形式化，而是在神学上有根有基，使之有极强的内在一贯性。这套神学系统是《耶稣传》中国化的思想驱动。这也是对今天基督教中国化的重要提醒，基督教中国化的神学思想建设，是一切中国化之形式的基础。''')

