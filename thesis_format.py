add_heading_text(doc, '六、詹姆斯的"实验主义"', 3)
write_body(doc, '''詹姆斯（William James）是19世纪末实验主义（实用主义）哲学的代表之一。詹姆斯强调经验，主张真理的检验标准不在于其是否符合某种抽象的形上学前设，而在于其产生的实际效果，即不看前提只看结果。认为"可以起作用的观念才可以成为真理"，真理就是"有用"，而"有用就是真理"的论点在实用主义哲学中占有重要地位。''')

write_body(doc, '''赵紫宸是受实验主义的影响的，他认同经验先于理性，神学理论要配合宗教经验，他说："理性化是实验的，因为我先有一番如其图中的阅历，而后在此阅历上得了理解，并未曾倒果为因，以为先有理性，然后有阅历。任何个人倘然先找理性，然后拿了理性去配置经验，必定要有画饼充饥的失望"。这种实验主义的态度，使赵紫宸获得了大胆审视和批判传统教义的勇气。''')

write_body(doc, '''赵紫宸提出了一个极具冲击力的问题：如果某些传统教义（如童贞女生子、肉身复活、末世审判等）在现代人心灵中无法产生任何实际效果，反而成为信仰的障碍，那么它们还有必要保留吗？他的答案是否定的。比如在耶稣肉身复活这件事上，赵紫宸将其解释为"耶稣的理想与精神，耶稣的品格与生命，存留在人间"，他规避肉体复活的概念，认为"耶稣复活即是耶稣精神永远存在的意思，此外更无有意思"。这种诠释的核心逻辑，正是实用主义的效果论：如果肉身复活这一教义无法在现代人的经验中产生实际效用，那么它就不具备作为真理的必要性。''')

write_body(doc, '''所以，实验主义构成了赵紫宸在《耶稣传》中进行"去神话化"处理的理论起点。他毫不留情地剥离那些在他看来无法通过经验检验的传统教义。在赵紫宸看来，基督教的本真不在于抽象的教义体系，而在于其通过耶稣生命所呈现的实际价值。''')

