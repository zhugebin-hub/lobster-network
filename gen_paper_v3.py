h1('五、对中国教会牧养实践的建议')

h2('（一）讲台信息的神学调整')

para('讲台是塑造信徒信仰认知的核心场域。建议在讲道中有意识地引入圣经中的"眼泪叙事"——尼希米的哭泣、耶稣的眼泪、保罗的流泪——帮助会众认识到，哭泣在圣经传统中是被肯定、被纪念、被使用的。')

para('同时，讲道中对"刚强"的理解也需要调整。圣经中的"刚强"不意味着"不哭"，而是意味着"哭了之后仍然信靠"。')

h2('（二）牧养关怀中情感空间的营造')

para('在个人牧养层面，教牧人员需要学会区分"健康的哭泣"与"沉溺式的悲伤"。健康的哭泣是一种情感的释放和向上帝的呼求；沉溺式的悲伤则可能演变为绝望和自我封闭，需要谨慎辨别，必要时引入专业心理咨询。')

para('更重要的是，教牧人员需要为信众提供安全的情感表达空间。保罗说："与喜乐的人要同乐，与哀哭的人要同哭。"（罗12:15）当信徒在苦难中流泪时，教牧人员的第一回应不应该是"你要坚强"，而应该是"我陪你一起面对"。')

h2('（三）眼泪神学与基督教中国化的深层对话')

para('基督教中国化是一个被广泛讨论的话题。在当前的实践中，它有时被简化为外在形式的调整——使用民族乐器、在教堂建筑中融入中国传统元素。这些做法有其价值，但如果中国化仅停留在这个层面，它就只是表面的。')

para('本文提出，从眼泪神学的角度切入，可以为基督教中国化提供一个更深层的路径。中国文化的"家国情怀"与圣经的"代求性眼泪"之间存在着深刻的精神共鸣——孟子说"恻隐之心，人皆有之"，范仲淹说"先天下之忧而忧，后天下之乐而乐"。这些中国传统的家国情感表达，与尼希米的眼泪、耶利米的眼泪、耶稣的眼泪，在精神深处是相通的。')

para('打通这种共鸣，不是将圣经"中国化"，而是让基督教信仰在中国人的情感深处扎根。这比任何外在形式的调整都更加根本，也更持久。正如丁光训主教所言，中国基督教需要在神学思想上与中国文化进行深度的对话和融合，而不是仅仅停留在礼仪和形式的层面。⑦')

