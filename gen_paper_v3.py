h1('结语')

para('本文从《尼希米记》第一章"坐下哭泣"的叙事出发，通过梳理旧约和新约中的眼泪传统，论证了以下核心观点。第一，眼泪在圣经传统中是力量的表达，而非软弱的象征。尼希米、耶利米、耶稣、保罗的眼泪叙事共同表明：哭泣是信心的表达、圣灵的工作、以及行动的起点。第二，尼希米的"坐下哭泣"为基督徒的家国情感提供了神学范本。他对故土的牵挂、对同胞苦难的共情、以及从眼泪到重建的行动，构成了一个完整的信仰范式。当代中国基督徒对民族命运的情感关切，在结构上与尼希米的眼泪是一致的，因而具有圣经根据。第三，中国教会需要重新认识和接纳眼泪的属灵价值。这不仅涉及神学认知的调整，更涉及牧养实践的更新。同时，眼泪神学也为基督教中国化提供了一个从情感深层入场的具体路径。')

para('本文的局限在于：其一，主要侧重旧约叙事，对新约书信中眼泪神学的系统挖掘尚有空间；其二，教父传统（如奥古斯丁《忏悔录》中的眼泪叙事）和宗教改革传统中的眼泪神学资源，因篇幅限制未能充分展开；其三，关于中国教会信徒对"哭泣"态度的实证研究，也是未来值得开展的方向。')

