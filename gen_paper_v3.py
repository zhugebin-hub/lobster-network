h1('三、眼泪为何被污名化？')

para('既然圣经传统赋予眼泪如此正面的地位，为什么中国教会中会出现"哭泣=软弱"的倾向？这个问题需要从历史和文化的角度来理解。')

h2('（一）西方理性主义传统的间接影响')

para('启蒙运动之后，西方思想经历了一个深刻的"理性化"转向。笛卡尔的身心二元论将理性置于情感之上，康德将道德的基础建立在纯粹理性之上。这些哲学转向深刻影响了基督教神学的走向。')

para('在这一框架下，"信心"往往被理解为一种理性的确信。这种理解本身并非错误，但它忽略了一个重要维度：信心不仅仅是头脑中的认同，更是整全生命的回应，其中必然包含情感。当情感被排除在信心之外时，"哭泣"就很容易被看作信心的对立面。')

para('这一倾向通过近代来华传教士间接影响了中国教会的形成。19世纪来华的传教士大多来自深受启蒙理性影响的欧美教会，他们的神学传统在中国教会的扎根过程中，无形中将"理性化的信心"设定为信仰的标准模式。')

h2('（二）教会"刚强叙事"的异化')

para('中国教会中有一个常见的讲道模式：强调"刚强"。"要刚强壮胆"（书1:9）、"不要怕"（赛41:10）——这些经文本身没有问题。然而，在实际的讲道和牧养实践中，这些话语有时被异化为压抑情感的工具。')

para('当"刚强"被简化为"不哭"时，它就从圣经的鼓励变成了人为的要求。圣经中的"刚强"从来不意味着"没有情感"或"不流泪"。恰恰相反，圣经中最"刚强"的人物——尼希米、耶利米、耶稣、保罗——都流过泪。他们的刚强不在于他们没有情感，而在于他们的情感引导他们走向了正确的行动。')

para('在牧养实践中，这种异化的"刚强叙事"可能导致信徒对自身情感产生怀疑，牧养关系中的真诚对话被阻断，教会的公共生活中缺乏对苦难的诚实面对。')

h2('（三）中国传统文化的叠加')

para('中国传统的儒家文化对情感的表达持较为克制的态度。"男儿有泪不轻弹"——这些观念深深扎根于中国文化心理之中。当这种文化惯性与教会的"刚强叙事"叠加时，"流泪=软弱"的误读就被进一步强化了。')

para('然而，儒家传统中也有可以与圣经眼泪观对话的资源。孟子说："恻隐之心，人皆有之。"（《孟子·告子上》）这种对他人苦难的天然同情，与圣经中"与哀哭的人同哭"（罗12:15）的精神在结构上是相通的。儒家讲"哀而不伤"（《论语·八佾》），意味着悲伤的表达是正当的，只要它不走向沉溺和绝望。')

