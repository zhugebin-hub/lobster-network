function addSlide(title, bullets, sectionTag) {
  const slide = pres.addSlide();
  slide.background = { fill: C.white };
  slide.addShape("rect", { x: 0, y: 0, w: "100%", h: 1.1, fill: C.primary });
  slide.addText(title, {
    x: 0.6, y: 0.15, w: 11, h: 0.75,
    fontSize: 26, color: C.white, bold: true,
    fontFace: "Microsoft YaHei",
  });

  if (sectionTag) {
    slide.addShape("rect", {
      x: 0.6, y: 1.2, w: 1.3, h: 0.36, fill: C.accent, rectRadius: 0.12,
    });
    slide.addText(sectionTag, {
      x: 0.6, y: 1.2, w: 1.3, h: 0.36,
      fontSize: 12, color: C.white, bold: true, align: "center",
      fontFace: "Microsoft YaHei",
    });
  }

  const textObj = bullets.map((b) => ({
    text: b,
    options: {
      fontSize: 15,
      color: C.textMid,
      fontFace: "Microsoft YaHei",
      lineSpacingMultiple: 1.55,
      bullet: { type: "bullet", character: "\u25CF", color: C.accent, indent: 15 },
    },
  }));

  slide.addText(textObj, {
    x: 0.6, y: sectionTag ? 1.7 : 1.1,
    w: 12.0, h: 5.0,
    valign: "top",
    paraSpaceBefore: 6,
    paraSpaceAfter: 4,
  });
}

